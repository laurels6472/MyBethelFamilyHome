var WOL_DOC = 'https://wol.jw.org/en/wol/d/r1/lp-e/';
var WOL_MEETINGS = 'https://wol.jw.org/en/wol/meetings/r1/lp-e/2026/';

function meetingWeekIndexFor(dateStr) {
  var i = MEETING_WEEKS.findIndex(function (w) { return dateStr >= w.start && dateStr <= w.end; });
  if (i !== -1) return i;
  if (dateStr < MEETING_WEEKS[0].start) return 0;
  return MEETING_WEEKS.length - 1;
}

function MeetingMaterialPanel(props) {
  var isAdmin = !!props.isAdmin;
  var compact = !!props.compact;
  var todayStr = new Date().toLocaleDateString('en-CA');
  var currentIdx = meetingWeekIndexFor(todayStr);
  var idxState = React.useState(currentIdx);
  var idx = idxState[0], setIdx = idxState[1];
  var ovState = React.useState({});
  var overrides = ovState[0], setOverrides = ovState[1];
  var editState = React.useState(false);
  var editing = editState[0], setEditing = editState[1];
  var draftState = React.useState({});
  var draft = draftState[0], setDraft = draftState[1];

  React.useEffect(function () {
    var unsub = null;
    try { unsub = syncOn('meeting_material', function (d) { setOverrides(d || {}); }); } catch (e) {}
    return function () { if (typeof unsub === 'function') unsub(); };
  }, []);

  var base = MEETING_WEEKS[idx];
  var ov = overrides[base.start] || {};
  var w = Object.assign({}, base, ov);
  var isCurrent = idx === currentIdx && todayStr >= base.start && todayStr <= base.end;
  var asLines = function (v) { return Array.isArray(v) ? v : (typeof v === 'string' ? v.split('\n').filter(Boolean) : []); };
  var ministry = asLines(w.ministry);
  var living = asLines(w.living);
  var wtUrl = w.wtId ? WOL_DOC + w.wtId : 'https://www.jw.org/en/library/magazines/watchtower/';
  var wbUrl = w.wb ? WOL_DOC + w.wb : 'https://www.jw.org/en/library/jw-meeting-workbook/';

  var card = { background: 'rgba(0,0,0,.22)', borderRadius: 10, padding: '10px 12px', marginBottom: 8 };
  var label = function (txt, color) { return React.createElement('div', { style: { fontSize: 9, fontWeight: 800, letterSpacing: 1, color: color, marginBottom: 5 } }, txt); };
  var line = function (k, v) {
    if (!v) return null;
    return React.createElement('div', { style: { fontSize: 11, color: 'rgba(255,255,255,.75)', lineHeight: 1.6, marginBottom: 2 } },
      React.createElement('span', { style: { color: 'rgba(255,255,255,.4)' } }, k + ': '), v);
  };
  var navBtn = function (txt, onClick, disabled) {
    return React.createElement('button', { onClick: onClick, disabled: disabled, style: { background: 'rgba(255,255,255,.08)', border: 'none', color: disabled ? 'rgba(255,255,255,.2)' : '#fff', borderRadius: 20, width: 28, height: 28, fontSize: 14, cursor: disabled ? 'default' : 'pointer' } }, txt);
  };

  function startEdit() {
    setDraft({
      bible: w.bible || '', treasures: w.treasures || '', cbs: w.cbs || '', songs: w.songs || '',
      ministry: ministry.join('\n'), living: living.join('\n'),
      wtTitle: w.wtTitle || '', wtIssue: w.wtIssue || '', wtScripture: w.wtScripture || '', wtSong: w.wtSong || ''
    });
    setEditing(true);
  }
  function saveEdit() {
    var out = {
      bible: draft.bible, treasures: draft.treasures, cbs: draft.cbs, songs: draft.songs,
      ministry: draft.ministry.split('\n').map(function (s) { return s.trim(); }).filter(Boolean),
      living: draft.living.split('\n').map(function (s) { return s.trim(); }).filter(Boolean),
      wtTitle: draft.wtTitle, wtIssue: draft.wtIssue, wtScripture: draft.wtScripture, wtSong: draft.wtSong,
      editedAt: Date.now()
    };
    try { syncSet('meeting_material/' + base.start, out); } catch (e) {}
    var next = Object.assign({}, overrides); next[base.start] = out; setOverrides(next);
    setEditing(false);
  }
  function resetWeek() {
    try { syncSet('meeting_material/' + base.start, null); } catch (e) {}
    var next = Object.assign({}, overrides); delete next[base.start]; setOverrides(next);
    setEditing(false);
  }
  var field = function (key, lbl, multi) {
    var common = { value: draft[key] || '', onChange: function (e) { var v = e.target.value; setDraft(function (p) { var n = Object.assign({}, p); n[key] = v; return n; }); }, style: { width: '100%', boxSizing: 'border-box', background: 'rgba(255,255,255,.07)', border: '1px solid rgba(255,255,255,.15)', borderRadius: 8, padding: '7px 9px', color: '#fff', fontSize: 12, marginBottom: 6 } };
    return React.createElement('div', { key: key },
      React.createElement('div', { style: { fontSize: 9, color: 'rgba(255,255,255,.4)', marginBottom: 2 } }, lbl),
      multi ? React.createElement('textarea', Object.assign({ rows: 3 }, common)) : React.createElement('input', Object.assign({ type: 'text' }, common)));
  };

  var linkStyle = { color: '#9FA8DA', textDecoration: 'none', fontWeight: 700 };

  if (compact) {
    return React.createElement('div', { style: { background: 'rgba(121,134,203,.08)', border: '1px solid rgba(121,134,203,.3)', borderRadius: 10, padding: '9px 12px', marginBottom: 10 } },
      React.createElement('div', { style: { fontSize: 9, fontWeight: 800, letterSpacing: 1, color: '#7986CB', marginBottom: 4 } }, '📅 THIS WEEK’S MEETING MATERIAL · ' + base.label.toUpperCase()),
      React.createElement('div', { style: { fontSize: 11, color: '#fff', lineHeight: 1.6 } },
        React.createElement('a', { href: wtUrl, target: '_blank', rel: 'noopener noreferrer', style: linkStyle }, '📖 Watchtower: ' + w.wtTitle),
        w.wtScripture ? React.createElement('span', { style: { color: 'rgba(255,255,255,.5)' } }, ' (' + w.wtScripture.split(' — ')[0] + ')') : null),
      React.createElement('div', { style: { fontSize: 11, color: 'rgba(255,255,255,.7)', lineHeight: 1.6 } },
        React.createElement('a', { href: wbUrl, target: '_blank', rel: 'noopener noreferrer', style: linkStyle }, '📒 Workbook'),
        ': Bible reading ' + w.bible + ' · Bible Study ' + String(w.cbs || '').toLowerCase()));
  }

  return React.createElement('div', { style: { margin: '12px 14px', background: 'rgba(121,134,203,.06)', border: '1px solid rgba(121,134,203,.28)', borderRadius: 14, padding: 12 } },
    React.createElement('div', { style: { display: 'flex', alignItems: 'center', gap: 8, marginBottom: 8 } },
      React.createElement('div', { style: { flex: 1 } },
        React.createElement('div', { style: { fontSize: 13, fontWeight: 900, color: '#9FA8DA' } }, '📅 This Week’s Meeting Material'),
        React.createElement('div', { style: { fontSize: 10, color: 'rgba(255,255,255,.45)' } }, base.label + ', 2026' + (isCurrent ? ' · this week' : ''))),
      navBtn('‹', function () { setIdx(Math.max(0, idx - 1)); setEditing(false); }, idx === 0),
      navBtn('›', function () { setIdx(Math.min(MEETING_WEEKS.length - 1, idx + 1)); setEditing(false); }, idx === MEETING_WEEKS.length - 1)),
    idx !== currentIdx && React.createElement('button', { onClick: function () { setIdx(currentIdx); setEditing(false); }, style: { background: 'transparent', border: '1px solid rgba(121,134,203,.4)', color: '#9FA8DA', borderRadius: 20, fontSize: 10, padding: '4px 10px', marginBottom: 8, cursor: 'pointer' } }, '↩ Back to this week'),

    editing
      ? React.createElement('div', { style: card },
          label('✏️ EDIT THIS WEEK', '#FFB74D'),
          field('wtTitle', 'Watchtower study article title'), field('wtIssue', 'Issue / pages (e.g. August 2026, pp. 2–7)'),
          field('wtScripture', 'Theme scripture'), field('wtSong', 'Opening song'),
          field('bible', 'Weekly Bible reading'), field('treasures', 'Treasures from God’s Word talk'),
          field('ministry', 'Apply Yourself to the Field Ministry parts (one per line)', true),
          field('living', 'Living as Christians parts (one per line)', true),
          field('cbs', 'Congregation Bible Study'), field('songs', 'Songs'),
          React.createElement('div', { style: { display: 'flex', gap: 8, marginTop: 4 } },
            React.createElement('button', { onClick: saveEdit, style: { flex: 1, background: '#4CAF82', color: '#000', border: 'none', borderRadius: 20, padding: 9, fontWeight: 800, fontSize: 11, cursor: 'pointer' } }, 'Save for everyone'),
            React.createElement('button', { onClick: function () { setEditing(false); }, style: { background: 'rgba(255,255,255,.08)', color: '#ccc', border: 'none', borderRadius: 20, padding: '9px 14px', fontSize: 11, cursor: 'pointer' } }, 'Cancel'),
            overrides[base.start] ? React.createElement('button', { onClick: resetWeek, style: { background: 'rgba(239,83,80,.12)', color: '#EF5350', border: 'none', borderRadius: 20, padding: '9px 14px', fontSize: 11, cursor: 'pointer' } }, 'Reset') : null))
      : React.createElement(React.Fragment, null,
          React.createElement('div', { style: Object.assign({}, card, { border: '1px solid rgba(156,141,196,.35)' }) },
            label('📖 THE WATCHTOWER (STUDY)' + (w.wtIssue ? ' · ' + w.wtIssue.toUpperCase() : ''), '#9C8DC4'),
            React.createElement('a', { href: wtUrl, target: '_blank', rel: 'noopener noreferrer', style: Object.assign({}, linkStyle, { fontSize: 13, display: 'block', marginBottom: 4 }) }, w.wtTitle + ' ›'),
            line('Theme scripture', w.wtScripture), line('Opening song', w.wtSong),
            (w.wtHeadings && w.wtHeadings.length) ? React.createElement('div', { style: { marginTop: 4 } },
              w.wtHeadings.map(function (h, i) { return React.createElement('div', { key: i, style: { fontSize: 10.5, color: 'rgba(255,255,255,.6)', lineHeight: 1.6 } }, (i + 1) + '. ' + h); })) : null),
          React.createElement('div', { style: card },
            label('📒 LIFE AND MINISTRY MEETING WORKBOOK', '#7986CB'),
            line('Bible reading', w.bible),
            React.createElement('div', { style: { fontSize: 10, fontWeight: 800, color: '#4CAF82', marginTop: 6 } }, 'TREASURES FROM GOD’S WORD'),
            line('Talk', w.treasures ? '“' + w.treasures + '”' : ''),
            ministry.length ? React.createElement('div', { style: { fontSize: 10, fontWeight: 800, color: '#F9A825', marginTop: 6 } }, 'APPLY YOURSELF TO THE FIELD MINISTRY') : null,
            ministry.map(function (m, i) { return React.createElement('div', { key: 'm' + i, style: { fontSize: 11, color: 'rgba(255,255,255,.7)', lineHeight: 1.6 } }, '• ' + m); }),
            living.length ? React.createElement('div', { style: { fontSize: 10, fontWeight: 800, color: '#E57373', marginTop: 6 } }, 'LIVING AS CHRISTIANS') : null,
            living.map(function (m, i) { return React.createElement('div', { key: 'l' + i, style: { fontSize: 11, color: 'rgba(255,255,255,.7)', lineHeight: 1.6 } }, '• ' + m); }),
            line('Congregation Bible Study', w.cbs), line('Songs', w.songs),
            React.createElement('a', { href: wbUrl, target: '_blank', rel: 'noopener noreferrer', style: Object.assign({}, linkStyle, { fontSize: 10.5, display: 'inline-block', marginTop: 6 }) }, 'Open this week’s workbook on wol.jw.org ›')),
          React.createElement('div', { style: { display: 'flex', alignItems: 'center', gap: 8 } },
            React.createElement('a', { href: WOL_MEETINGS + base.wk, target: '_blank', rel: 'noopener noreferrer', style: Object.assign({}, linkStyle, { fontSize: 10 }) }, 'Full week on wol.jw.org ›'),
            React.createElement('div', { style: { flex: 1 } }),
            isAdmin && React.createElement('button', { onClick: startEdit, style: { background: 'rgba(255,183,77,.12)', border: '1px solid rgba(255,183,77,.35)', color: '#FFB74D', borderRadius: 20, fontSize: 10, fontWeight: 700, padding: '5px 12px', cursor: 'pointer' } }, ov && ov.editedAt ? '✏️ Edited — change' : '✏️ Edit this week')),
          React.createElement('div', { style: { fontSize: 8.5, color: 'rgba(255,255,255,.3)', marginTop: 8, lineHeight: 1.5 } }, 'Pre-loaded from the wol.jw.org meeting schedule. Check the wording in JW Library, and edit any week if it differs.')));
}
